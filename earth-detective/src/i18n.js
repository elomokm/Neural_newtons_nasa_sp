let lang = 'fr';
export const getLang = () => lang;
export function setLang(l) {
  lang = l === 'en' ? 'en' : 'fr';
  document.documentElement.lang = lang;
}
export function t(key, ...args) {
  const v = D[lang][key];
  if (typeof v === 'function') return v(...args);
  return v == null ? key : v;
}
export const tl = (obj) => (obj && (obj[lang] ?? obj.fr)) || '';
